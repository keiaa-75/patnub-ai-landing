<script>
  import { onMount, tick } from 'svelte';

  import { gsap } from 'gsap';
  import { ScrollTrigger } from 'gsap/ScrollTrigger';

  import Phone from './Phone.svelte';
  import DemoScreens from './DemoScreens.svelte';
  import BrewCodeArtwork from './BrewCodeArtwork.svelte';
  import FloatingControls from './FloatingControls.svelte';
  import Shapes from './Shapes.svelte';
  import MobileExperience from './MobileExperience.svelte';

  import { spatial, effects } from './motion.js';
  import { computeLayout } from './layout.js';

  /*
    Story beats:

      0  Opening question
      1  Hero
      2  Feature 1
      3  Feature 2
      4  Feature 3
      5  Feature 4
      6  Download and BrewCode showcase

    The final beat settles before the end of its scroll interval.
    There is no separate About section.
  */

  const BEATS = 6;
  const FIRST_FEATURE_BEAT = 2;
  const DOWNLOAD_BEAT = 6;

  const SNAP = true;
  const SCRUB = 0.4;

  const FLAGS = typeof window === 'undefined'
    ? new URLSearchParams()
    : new URLSearchParams(window.location.search);

  const PHONE_DEBUG_VIEW = FLAGS.get('phoneview');

  const PHONE_DEBUG_POSES = {
    front: { yaw: 0, pitch: 0, roll: -2 },
    back: { yaw: 180, pitch: 0, roll: -2 },
    left: { yaw: -90, pitch: 0, roll: -2 },
    right: { yaw: 90, pitch: 0, roll: -2 },
    top: { yaw: 0, pitch: -90, roll: 0 },
    bottom: { yaw: 0, pitch: 90, roll: 0 },
    angle: { yaw: 34, pitch: 12, roll: -5 }
  };

  const PHONE_DEBUG_POSE = Object.hasOwn(PHONE_DEBUG_POSES, PHONE_DEBUG_VIEW)
    ? PHONE_DEBUG_POSES[PHONE_DEBUG_VIEW]
    : null;
  const PHONE_DEBUG = Boolean(PHONE_DEBUG_POSE);
  const NO_SHAPES = FLAGS.has('noshapes') || PHONE_DEBUG;
  const NO_3D = FLAGS.has('no3d') || PHONE_DEBUG;

  const MOBILE_QUERY = [
    '(max-width: 640px)',
    '(max-width: 900px) and (max-height: 480px) and (orientation: landscape)'
  ].join(', ');

  function getLayoutMode() {
    if (typeof window === 'undefined') return 'desktop';
    if (!PHONE_DEBUG && window.matchMedia(MOBILE_QUERY).matches) return 'mobile';

    if (window.innerWidth <= 1199) {
      return window.matchMedia('(orientation: portrait)').matches
        ? 'tablet-portrait'
        : 'tablet-landscape';
    }

    return 'desktop';
  }

  let layoutMode = $state(getLayoutMode());
  let isMobile = $derived(layoutMode === 'mobile' && !PHONE_DEBUG);

  const T = (beat, fraction = 0) =>
    (beat + fraction) / BEATS;

  const D = (fraction) =>
    fraction / BEATS;

  const settle = (fn) =>
    requestAnimationFrame(() =>
      requestAnimationFrame(fn)
    );

  const whenFontsReady = (timeout) => {
    const loading = document.fonts?.load
      ? Promise.all([
          document.fonts.load('600 64px Fredoka'),
          document.fonts.load('400 16px Roboto')
        ])
      : Promise.resolve();

    return Promise.race([
      loading.catch(() => {}),
      new Promise((resolve) => setTimeout(resolve, timeout))
    ]);
  };

  let scene = $state(null);
  let stage = $state(null);

  let bgTeal = $state(null);
  let bgWhite = $state(null);

  let problem = $state(null);
  let tagline = $state(null);
  let featureCopy = $state(null);
  let downloadCopy = $state(null);

  let shapes = $state(null);
  let scrollHint = $state(null);

  let phoneSlot = $state(null);
  let contactShadow = $state(null);
  let screenFade = $state(null);

  let phone3d = $state(null);
  let Phone3DLazy = $state(null);
  let phone3DImportPromise = null;

  let screen = $state(0);
  let step = $state(0);

  let reduced = $state(false);
  let use3d = $state(!NO_3D);
  let threeReady = $state(false);

  const clamp = gsap.utils.clamp;

  /*
    Phone dimensions.

    Portrait tablets get a larger device that shares the viewport
    with the feature copy. Landscape tablets and desktop retain their
    own sizing rules; mobile does not mount the phone at all.
  */

  /*
    All sizing and anchor points come from layout.js. `geometry` is
    refreshed whenever the viewport or layout mode changes.
  */

  const getGeometry = () => {
    if (typeof window === 'undefined') {
      return computeLayout('desktop', 1280, 720);
    }

    return computeLayout(
      layoutMode,
      window.innerWidth,
      window.innerHeight
    );
  };

  let geometry = $state(getGeometry());
  let deviceHeight = $derived(geometry.deviceHeight);

  // Hidden copies of every feature block, used only to measure the
  // tallest one in portrait so the phone never shifts between beats.
  let featureProbes = $state([]);

  /*
    Application screen order:

      0 Assistant
      1 Records
      2 Scan
      3 Medicines
      4 BrewCode Hackathon artwork

    The final entry is generated by the shared artwork renderer.
  */

  const SCREEN_URLS = [
    '/screens/assistant.png',
    '/screens/records.png',
    '/screens/scan.png',
    '/screens/medicines.png',
    'brewcode-artwork'
  ];

  const features = [
    {
      title: 'Ask in plain language.',
      body: 'Ask about symptoms or medicines. Get clear explanations grounded in trusted health references and your own saved record.'
    },
    {
      title: 'Keep your doctor’s note.',
      body: 'Save clinician-approved instructions on your device, so the details are easier to revisit when you need them.'
    },
    {
      title: 'Save a note with a scan.',
      body: 'Use a secure QR code from your clinic to add approved instructions to your personal records.'
    },
    {
      title: 'Understand your medicines.',
      body: 'Find plain-language information from reviewed references, without losing sight of your clinician’s advice.'
    }
  ];

  function updateDeviceHeight() {
    geometry = getGeometry();
  }

  function ensurePhone3D() {
    if (NO_3D || isMobile || Phone3DLazy || phone3DImportPromise) return;

    phone3DImportPromise = import('./Phone3D.svelte')
      .then((module) => {
        Phone3DLazy = module.default;
      })
      .catch((error) => {
        console.warn('[patnub.ai] Could not load 3D phone:', error);
        use3d = false;
        startShapes();
      });
  }

  function syncViewportLayout() {
    const nextLayout = getLayoutMode();
    const changed = nextLayout !== layoutMode;

    if (changed) {
      layoutMode = nextLayout;

      if (nextLayout === 'mobile') {
        threeReady = false;
        phone3d = null;
      }
    }

    updateDeviceHeight();

    if (nextLayout !== 'mobile') {
      gsap.registerPlugin(ScrollTrigger);

      const prefersReducedMotion = window.matchMedia(
        '(prefers-reduced-motion: reduce)'
      ).matches;

      if (NO_3D) startShapes();
      else if (!prefersReducedMotion) ensurePhone3D();
    }
  }

  const startShapes = () =>
    settle(() => shapes?.enter());

  onMount(() => {
    /*
      Only desktop and tablet construct the 3D story. Mobile gets
      a separate document-flow layout with no pinned ScrollTrigger.
    */

    if (!isMobile) {
      gsap.registerPlugin(ScrollTrigger);
      syncViewportLayout();
    }

    const reducedMotionQuery = window.matchMedia('(prefers-reduced-motion: reduce)');

    window.addEventListener('resize', syncViewportLayout, { passive: true });
    reducedMotionQuery.addEventListener?.('change', syncViewportLayout);

    /*
      Build the appropriate 3D story for each non-mobile layout.
    */

    const buildStory = (layout) => {
      const isDesktop = layout === 'desktop';
      const isTabletPortrait = layout === 'tablet-portrait';
      const els = {
        scene,
        stage,
        bgTeal,
        bgWhite,
        problem,
        tagline,
        featureCopy,
        downloadCopy,
        scrollHint,
        phoneSlot,
        contactShadow,
        screenFade
      };

      if (!els.scene || !els.stage || !els.phoneSlot) return () => {};

      reduced = false;

      /*
        Geometry comes from layout.js and is re-read on every measure().
        Tablet layouts then refine the vertical placement from the real
        height of the copy (see placeTabletGroups).
      */

      let g = geometry;

      let finalY = g.finalY;

      let story = null;

      const pose = {
        xVw: g.enterX,
        yVh: g.restY,

        z: -35,

        yaw: -450,
        pitch: g.pitch,
        roll: -7,

        scale: g.enterScale,

        screenF: 0,

        reveal1: 0,
        reveal2: 0,

        persp: 1180
      };

      const idle = {
        y: 0,
        yaw: 0
      };

      const pointer = {
        x: 0,
        y: 0
      };

      const wobble = {
        value: 0,
        target: 0
      };

      const size = {
        w: 0,
        h: 0
      };

      let active = true;
      let lastBeat = 0;

      let lastClipTeal = '';
      let lastClipWhite = '';

      let cancelled = false;

      const heightOf = (el) =>
        el ? el.getBoundingClientRect().height : 0;

      /*
        Tablet vertical composition.

        Portrait:  phone + copy are one block, centred in the viewport.
                   The same is done for the final beat (rotated phone +
                   download copy).
        Landscape: the phone stays on the vertical centre line beside the
                   copy; only the final beat (download copy above the
                   rotated phone) is centred as a block.
      */

      const placeTabletGroups = () => {
        const edge = clamp(44, 84, size.h * 0.06);
        const gap = clamp(22, 40, size.h * 0.03);
        const avail = size.h - edge * 2;

        const phoneH = g.deviceHeight * g.restScale;
        const rotatedH = g.deviceHeight * g.finalScale * (9 / 19.5);

        const downloadH = heightOf(els.downloadCopy);

        const beforeFinal = !story || story.progress() * BEATS < 5;

        if (isTabletPortrait) {
          const probeHeights = featureProbes
            .filter(Boolean)
            .map(heightOf);

          const copyH = Math.max(
            heightOf(els.tagline),
            heightOf(els.featureCopy),
            ...probeHeights
          );

          const groupH = phoneH + gap + copyH;
          const groupTop = edge + Math.max(0, (avail - groupH) / 2);

          if (beforeFinal) {
            pose.yVh = (groupTop + phoneH / 2) / size.h - 0.5;
          }

          els.stage.style.setProperty(
            '--copy-top',
            `${(groupTop + phoneH + gap).toFixed(1)}px`
          );

          const finalH = rotatedH + gap + downloadH;
          const finalTop = edge + Math.max(0, (avail - finalH) / 2);

          finalY = (finalTop + rotatedH / 2) / size.h - 0.5;

          els.stage.style.setProperty(
            '--download-top',
            `${(finalTop + rotatedH + gap).toFixed(1)}px`
          );

          return;
        }

        // Landscape tablet: copy on top, rotated phone underneath.
        const finalH = downloadH + gap + rotatedH;
        const finalTop = edge + Math.max(0, (avail - finalH) / 2);

        finalY =
          (finalTop + downloadH + gap + rotatedH / 2) / size.h - 0.5;

        els.stage.style.setProperty(
          '--download-top',
          `${finalTop.toFixed(1)}px`
        );
      };

      const measure = () => {
        size.w = els.stage.clientWidth;
        size.h = els.stage.clientHeight;

        g = geometry;
        finalY = g.finalY;

        if (!isDesktop && size.h > 0) placeTabletGroups();
      };

      measure();

      // Probes and --col-* variables land one frame after mount.
      if (!isDesktop) settle(measure);

      window.addEventListener(
        'resize',
        measure,
        { passive: true }
      );

      /*
        Initial visibility.
      */

      gsap.set(
        [els.tagline, els.featureCopy, els.downloadCopy].filter(Boolean),
        { autoAlpha: 0 }
      );

      gsap.set(els.problem, {
        autoAlpha: 1,
        y: 0
      });

      if (els.scrollHint) {
        gsap.set(els.scrollHint, {
          autoAlpha: 1
        });
      }

      screen = 0;
      step = 0;

      const headline = els.problem.querySelector('h1');

      gsap.set(headline, {
        y: 28
      });

      /*
        Avoid font swapping during the opening animation.
      */

      whenFontsReady(1500).then(() => {
        if (cancelled) return;

        // Re-measure the copy once font metrics settle.
        measure();

        gsap.to(headline, {
          opacity: 1,
          duration: 0.6,
          ease: effects
        });

        gsap.to(headline, {
          y: 0,
          duration: 0.95,
          ease: spatial
        });
      });

      /*
        Main scroll-driven timeline.

        The same timeline controls:

        - Phone position
        - Phone rotation
        - Phone scale
        - Background reveals
        - App screen transitions
      */

      const timeline = gsap.timeline({
        defaults: {
          ease: 'none'
        },

        scrollTrigger: {
          id: 'patnub-story',

          trigger: els.scene,

          start: 'top top',
          end: 'bottom bottom',

          scrub: SCRUB,

          invalidateOnRefresh: true,

          snap: SNAP
            ? {
                snapTo: 1 / BEATS,

                duration: {
                  min: 0.2,
                  max: 0.6
                },

                delay: 0.1,

                ease: 'power2.inOut'
              }
            : undefined,

          onUpdate: (self) => {
            const currentBeat = Math.round(
              self.progress * BEATS
            );

            /*
              Expressive shape reactions occur only when a beat changes.
            */

            if (currentBeat !== lastBeat) {
              lastBeat = currentBeat;

              shapes?.goTo(currentBeat);

            }

            wobble.target = clamp(
              -5,
              5,
              self.getVelocity() / 420
            );

            shapes?.setProgress(self.progress);
          }
        }
      });

      /*
        OPENING -> HERO

        The phone enters from the left and brings
        the teal background with it.
      */

      timeline.to(
        pose,
        {
          xVw: () => g.restX,

          yaw: 0,
          z: 0,
          roll: 0,

          scale: () => g.restScale,

          duration: D(0.9),

          ease: 'power2.out'
        },
        T(0, 0.1)
      );

      timeline.to(
        pose,
        {
          reveal1: 1,

          duration: D(0.75),

          ease: 'power2.inOut'
        },
        T(0, 0.2)
      );

      /*
        HERO -> FIRST FEATURE

        The device moves to the left and the white
        background replaces teal.
      */

      timeline.to(
        pose,
        {
          xVw: () => g.featureX,

          yaw: -360,

          duration: D(0.9),

          ease: 'power2.inOut'
        },
        T(1, 0.05)
      );

      timeline.to(
        pose,
        {
          reveal2: 1,

          duration: D(0.75),

          ease: 'power2.inOut'
        },
        T(1, 0.15)
      );

      /*
        SCREEN TRANSITIONS

        The main timeline is the only owner of screenF.

        0 -> 1: Assistant to Records
        1 -> 2: Records to Scan
        2 -> 3: Scan to Medicines
        3 -> 4: Medicines to BrewCode Hackathon artwork

        This avoids the competing GSAP tweens that could
        previously leave the Medicines screen displayed.
      */

      timeline.to(
        pose,
        {
          screenF: 1,

          duration: D(0.55)
        },
        T(2, 0.45)
      );

      timeline.to(
        pose,
        {
          screenF: 2,

          duration: D(0.55)
        },
        T(3, 0.45)
      );

      timeline.to(
        pose,
        {
          screenF: 3,

          duration: D(0.55)
        },
        T(4, 0.45)
      );

      /*
        FINAL TRANSITION

        The phone moves toward the horizontal center, settles
        into its lower resting position, and rotates into landscape.

        The phone and screen transitions both finish
        by approximately beat 5.6, leaving a short
        resting interval before the end of the scene.
      */

      timeline.to(
        pose,
        {
          xVw: 0,
          yVh: () => finalY,

          yaw: 0,
          pitch: 0,
          roll: 90,

          scale: () => g.finalScale,

          duration: D(0.6),

          ease: 'power2.inOut'
        },
        T(5, 0)
      );

      timeline.to(
        pose,
        {
          screenF: 4,

          duration: D(0.42)
        },
        T(5, 0.18)
      );

      /*
        Keep the total timeline exactly 1.
      */

      timeline.set({}, { x: 0 }, 1);

      story = timeline;

      /*
        TIME-BASED TEXT ANIMATIONS

        These animations are separate from the
        phone's scroll-driven timeline.
      */

      const gates = {
        problem: true,
        hint: true,
        tagline: false,
        feature: false,
        download: false
      };

      const nudge = {
        s: 0,
        p: 0
      };

      let featureIndex = 0;

      const partsOf = (block) =>
        block
          ? gsap.utils.toArray(block.children)
          : [];

      const playIn = (parts, dir = 1) => {
        gsap.killTweensOf(parts);

        gsap.set(parts, {
          autoAlpha: 0,
          y: 28 * dir
        });

        gsap.to(parts, {
          autoAlpha: 1,
          duration: 0.45,
          ease: effects,
          stagger: 0.07
        });

        gsap.to(parts, {
          y: 0,
          duration: 0.9,
          ease: spatial,
          stagger: 0.07
        });
      };

      const showBlock = (block) => {
        if (!block) return;

        gsap.set(block, {
          autoAlpha: 1
        });

        playIn(partsOf(block));
      };

      const hideBlock = (block, name) => {
        if (!block) return;

        const parts = partsOf(block);

        gsap.killTweensOf(parts);

        gsap.to(parts, {
          autoAlpha: 0,
          y: -18,

          duration: 0.25,

          ease: effects,

          stagger: 0.03,

          onComplete: () => {
            if (!gates[name]) {
              gsap.set(block, {
                autoAlpha: 0
              });
            }
          }
        });
      };

      const setProblem = (show) => {
        gsap.killTweensOf(els.problem);

        if (show) {
          gsap.to(els.problem, {
            autoAlpha: 1,
            duration: 0.4,
            ease: effects
          });

          gsap.to(els.problem, {
            y: 0,
            duration: 0.9,
            ease: spatial
          });
        } else {
          gsap.to(els.problem, {
            autoAlpha: 0,
            y: -28,
            duration: 0.3,
            ease: effects
          });
        }
      };

      const setHint = (show) => {
        if (!els.scrollHint) return;

        gsap.to(els.scrollHint, {
          autoAlpha: show ? 1 : 0,

          duration: 0.3,
          ease: effects,

          overwrite: 'auto'
        });
      };

      /*
        Feature text transitions.

        Screen transitions are deliberately not handled here.
        Those are controlled entirely by the main timeline.
      */

      const swapFeature = (index, dir) => {
        const parts = partsOf(els.featureCopy);

        gsap.killTweensOf(parts);

        gsap.to(parts, {
          autoAlpha: 0,

          y: -16 * dir,

          duration: 0.2,

          ease: effects,

          stagger: 0.02,

          onComplete: async () => {
            step = index;

            await tick();

            if (
              gates.feature &&
              featureIndex === index
            ) {
              playIn(parts, dir);
            }
          }
        });
      };

      const changeFeature = (index, dir) => {
        featureIndex = index;

        gsap.fromTo(
          nudge,

          {
            s: 0.03,
            p: -2.5
          },

          {
            s: 0,
            p: 0,

            duration: 0.9,

            ease: spatial,

            overwrite: true
          }
        );

        if (gates.feature) {
          swapFeature(index, dir);
        } else {
          step = index;
        }
      };

      /*
        Content visibility.

        The opening headline disappears after the hero.
        Feature content leaves before the final transition.
        Download copy appears early enough to accompany the phone.
      */

      const inWindow = (name, beat, low, high) => {
        const margin = gates[name] ? 0.05 : 0;

        return (
          beat >= low - margin &&
          beat <= high + margin
        );
      };

      const syncStory = () => {
        const beat = timeline.progress() * BEATS;

        /*
          Opening question.
        */

        const problemOn = inWindow(
          'problem',
          beat,
          -1,
          0.15
        );

        if (problemOn !== gates.problem) {
          gates.problem = problemOn;

          setProblem(problemOn);
        }

        /*
          Scroll hint.
        */

        const hintOn = inWindow(
          'hint',
          beat,
          -1,
          0.08
        );

        if (hintOn !== gates.hint) {
          gates.hint = hintOn;

          setHint(hintOn);
        }

        /*
          Hero tagline.
        */

        const taglineOn = inWindow(
          'tagline',
          beat,
          0.85,
          1.25
        );

        if (taglineOn !== gates.tagline) {
          gates.tagline = taglineOn;

          if (taglineOn) {
            showBlock(els.tagline);
          } else {
            hideBlock(els.tagline, 'tagline');
          }
        }

        /*
          Features.
        */

        const featureOn = inWindow(
          'feature',
          beat,
          1.85,
          5.1
        );

        if (featureOn !== gates.feature) {
          gates.feature = featureOn;

          if (featureOn) {
            step = featureIndex;

            showBlock(els.featureCopy);
          } else {
            hideBlock(els.featureCopy, 'feature');
          }
        }

        /*
          Download heading and action.

          The section starts entering while the phone
          is still completing its final transition.
        */

        const downloadOn = inWindow(
          'download',
          beat,
          5.18,
          DOWNLOAD_BEAT + 1
        );

        if (downloadOn !== gates.download) {
          gates.download = downloadOn;

          if (downloadOn) {
            showBlock(els.downloadCopy);
          } else {
            hideBlock(els.downloadCopy, 'download');
          }
        }

        /*
          Update feature text only before the final transition.

          The main timeline continues to control screenF,
          including all reverse-scroll transitions.
        */

        if (beat < 5.15) {
          const index = clamp(
            0,
            features.length - 1,

            Math.round(beat) - FIRST_FEATURE_BEAT
          );

          if (index !== featureIndex) {
            changeFeature(
              index,
              index > featureIndex ? 1 : -1
            );
          }
        }
      };

      /*
        Expanding backdrop clipping.
      */

      const clipFor = (amount) => {
        if (amount <= 0.001) {
          return 'circle(0px at 50% 50%)';
        }

        const cx = size.w * (0.5 + pose.xVw);
        const cy = size.h * (0.5 + pose.yVh);

        const reach = Math.hypot(
          Math.max(cx, size.w - cx),
          Math.max(cy, size.h - cy)
        );

        return `circle(${(reach * amount * 1.02).toFixed(1)}px at ${cx.toFixed(1)}px ${cy.toFixed(1)}px)`;
      };

      /*
        Main render loop.

        The same phone pose is applied to either the
        actual Three.js model or the CSS fallback.
      */

      const render = () => {
        if (!active) return;

        syncStory();

        const yaw = pose.yaw + idle.yaw + pointer.y;
        const pitch = pose.pitch + pointer.x + nudge.p;

        const scale = pose.scale + nudge.s;

        wobble.value += (
          wobble.target - wobble.value
        ) * 0.085;

        wobble.target *= 0.88;

        const roll = pose.roll + wobble.value;

        if (
          use3d &&
          threeReady &&
          phone3d
        ) {
          phone3d.setPose({
            ...pose,
            yaw,
            pitch,
            roll,
            scale
          });
        } else if (els.phoneSlot) {
          gsap.set(els.phoneSlot, {
            x: pose.xVw * size.w,

            y: pose.yVh * size.h + idle.y,

            z: pose.z,

            rotationY: yaw + (use3d ? 0 : -6),
            rotationX: pitch + (use3d ? 0 : 2.5),
            rotationZ: roll,

            scale
          });
        }

        /*
          Backdrop reveals.
        */

        const clipTeal = clipFor(pose.reveal1);
        const clipWhite = clipFor(pose.reveal2);

        if (
          els.bgTeal &&
          clipTeal !== lastClipTeal
        ) {
          els.bgTeal.style.clipPath = clipTeal;

          lastClipTeal = clipTeal;
        }

        if (
          els.bgWhite &&
          clipWhite !== lastClipWhite
        ) {
          els.bgWhite.style.clipPath = clipWhite;

          lastClipWhite = clipWhite;
        }

        /*
          Screen sheen for the CSS fallback.
        */

        const radians = yaw * Math.PI / 180;

        if (els.phoneSlot) {
          els.phoneSlot.style.setProperty(
            '--sheen',
            `${50 + Math.sin(radians) * 26}%`
          );

          els.phoneSlot.style.setProperty(
            '--glass-pos',
            `${50 + Math.sin(radians) * 18}%`
          );
        }

        /*
          Contact shadow.
        */

        if (els.contactShadow) {
          const edge = Math.abs(Math.cos(radians));

          gsap.set(els.contactShadow, {
            x: size.w * (0.5 + pose.xVw),

            y:
              size.h * (0.5 + pose.yVh) +
              deviceHeight * scale * 0.5 +
              6,

            xPercent: -50,

            scaleX: 0.72 + 0.28 * edge,

            opacity: 0.1 + 0.08 * edge
          });
        }

        /*
          CSS fallback screen crossfade.
        */

        if (els.screenFade) {
          const difference = Math.abs(
            pose.screenF - Math.round(pose.screenF)
          );

          els.screenFade.style.opacity =
            1 - difference * 0.85;
        }

        /*
          Screen selection.

          The final value must be 4.
        */

        const nextScreen = clamp(
          0,
          SCREEN_URLS.length - 1,

          Math.round(pose.screenF)
        );

        if (nextScreen !== screen) {
          screen = nextScreen;
        }
      };

      /*
        Mouse movement produces a small expressive tilt.
      */

      const tiltPitch = gsap.quickTo(
        pointer,
        'x',
        {
          duration: 0.65,
          ease: 'power2.out'
        }
      );

      const tiltYaw = gsap.quickTo(
        pointer,
        'y',
        {
          duration: 0.65,
          ease: 'power2.out'
        }
      );

      const onPointer = (event) => {
        if (
          event.pointerType === 'touch'
        ) {
          return;
        }

        const bounds = els.stage.getBoundingClientRect();

        const x = (
          (event.clientX - bounds.left) /
          bounds.width -
          0.5
        ) * 2;

        const y = (
          (event.clientY - bounds.top) /
          bounds.height -
          0.5
        ) * 2;

        tiltPitch(-y * 2.5);
        tiltYaw(x * 3.5);
      };

      els.stage.addEventListener(
        'pointermove',
        onPointer,
        { passive: true }
      );

      /*
        Gentle idle movement.
      */

      const idleTween = gsap.to(idle, {
        y: 5,
        yaw: 2.2,

        duration: 3.2,
        ease: 'sine.inOut',

        yoyo: true,
        repeat: -1
      });

      /*
        Stop rendering when the stage is outside the viewport.
      */

      const observer = new IntersectionObserver(
        ([entry]) => {
          active = entry.isIntersecting;
        }
      );

      observer.observe(els.stage);

      gsap.ticker.add(render);

      render();

      /*
        Cleanup.
      */

      return () => {
        cancelled = true;

        const blocks = [
          els.problem,
          els.scrollHint,
          els.tagline,
          els.featureCopy,
          els.downloadCopy
        ].filter(Boolean);

        const parts = [
          ...partsOf(els.tagline),
          ...partsOf(els.featureCopy),
          ...partsOf(els.downloadCopy)
        ];

        gsap.killTweensOf([
          headline,
          ...blocks,
          ...parts,
          pose,
          nudge
        ]);

        gsap.set(
          [headline, ...blocks, ...parts],
          { clearProps: 'all' }
        );

        els.stage.removeEventListener(
          'pointermove',
          onPointer
        );

        window.removeEventListener('resize', measure);

        els.stage.style.removeProperty('--copy-top');
        els.stage.style.removeProperty('--download-top');

        observer.disconnect();

        gsap.ticker.remove(render);

        idleTween.kill();

        timeline.scrollTrigger?.kill();
        timeline.kill();
      };
    };

    /*
      Reduced-motion version.

      This shows all feature content and the final BrewCode artwork
      without requiring a scroll-driven animation.
    */

    const buildReducedMotion = () => {
      reduced = true;

      screen = 4;
      step = 0;

      return () => {
        reduced = false;
      };
    };

    /*
      Fixed-angle inspection mode.

      ?phoneview=front
      ?phoneview=back
      ?phoneview=left
      ?phoneview=right
      ?phoneview=top
      ?phoneview=bottom
      ?phoneview=angle

      This mode uses a static CSS phone and does not construct
      the normal scroll-driven story.
    */

    const buildPhoneInspection = () => {
      const inspectionPhoneSlot = phoneSlot;
      if (!inspectionPhoneSlot) return () => {};

      reduced = false;
      screen = 0;
      step = 0;

      const hiddenContent = [
        problem,
        tagline,
        featureCopy,
        downloadCopy,
        scrollHint,
        contactShadow
      ].filter(Boolean);

      gsap.set(hiddenContent, {
        autoAlpha: 0
      });

      gsap.set(inspectionPhoneSlot, {
        x: 0,
        y: 0,
        z: 0,
        rotationY: PHONE_DEBUG_POSE.yaw,
        rotationX: PHONE_DEBUG_POSE.pitch,
        rotationZ: PHONE_DEBUG_POSE.roll,
        scale: 0.92,
        transformOrigin: '50% 50%'
      });

      const debugYaw = PHONE_DEBUG_POSE.yaw * Math.PI / 180;

      inspectionPhoneSlot.style.setProperty(
        '--sheen',
        `${50 + Math.sin(debugYaw) * 26}%`
      );

      inspectionPhoneSlot.style.setProperty(
        '--glass-pos',
        `${50 + Math.sin(debugYaw) * 18}%`
      );

      return () => {
        gsap.set(inspectionPhoneSlot, {
          clearProps: 'transform'
        });

        inspectionPhoneSlot.style.removeProperty('--sheen');
        inspectionPhoneSlot.style.removeProperty('--glass-pos');

        gsap.set(hiddenContent, {
          clearProps: 'opacity,visibility'
        });
      };
    };

    const media = gsap.matchMedia();

    const mountStory = (layout) => {
      let cancelled = false;
      let cleanup = null;

      // A media-query change can precede Svelte's DOM update by one microtask.
      tick().then(() => {
        if (!cancelled) cleanup = buildStory(layout);
      });

      return () => {
        cancelled = true;
        cleanup?.();
      };
    };

    if (PHONE_DEBUG) {
      media.add('(min-width: 0px)', buildPhoneInspection);
    } else {
      media.add(
        '(min-width: 1200px) and (prefers-reduced-motion: no-preference)',
        () => mountStory('desktop')
      );

      media.add(
        '(min-width: 641px) and (max-width: 1199px) and (orientation: portrait) and (prefers-reduced-motion: no-preference)',
        () => mountStory('tablet-portrait')
      );

      media.add(
        '(min-width: 641px) and (max-width: 1199px) and (orientation: landscape) and (prefers-reduced-motion: no-preference)',
        () => mountStory('tablet-landscape')
      );

      media.add(
        '(min-width: 641px) and (prefers-reduced-motion: reduce)',
        buildReducedMotion
      );
    }

    /*
      Component cleanup.
    */

    return () => {
      media.revert();

      window.removeEventListener('resize', syncViewportLayout);
      reducedMotionQuery.removeEventListener?.('change', syncViewportLayout);

    };
  });
</script>

